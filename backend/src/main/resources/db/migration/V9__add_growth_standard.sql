-- 生长标准数据表
-- 支持多标准、LMS算法参数和百分位数据

-- 生长标准类型表
CREATE TABLE IF NOT EXISTS `growth_standard_type` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `code` VARCHAR(50) NOT NULL UNIQUE COMMENT '标准代码，如 CHINA_2025',
    `name` VARCHAR(100) NOT NULL COMMENT '标准名称',
    `description` VARCHAR(500) COMMENT '标准描述',
    `source` VARCHAR(200) COMMENT '数据来源',
    `min_age_months` INT DEFAULT 0 COMMENT '最小月龄',
    `max_age_months` INT DEFAULT 36 COMMENT '最大月龄',
    `supports_height` TINYINT DEFAULT 1 COMMENT '是否支持身高',
    `supports_weight` TINYINT DEFAULT 1 COMMENT '是否支持体重',
    `supports_bmi` TINYINT DEFAULT 0 COMMENT '是否支持BMI',
    `is_default` TINYINT DEFAULT 0 COMMENT '是否默认标准',
    `sort_order` INT DEFAULT 0 COMMENT '排序顺序',
    `status` TINYINT DEFAULT 1 COMMENT '状态: 1-启用 0-禁用',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='生长标准类型表';

-- 生长标准数据表（存储百分位或LMS参数）
CREATE TABLE IF NOT EXISTS `growth_standard_data` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `standard_type_id` BIGINT NOT NULL COMMENT '标准类型ID',
    `gender` TINYINT NOT NULL COMMENT '性别: 1-男 0-女',
    `indicator` VARCHAR(20) NOT NULL COMMENT '指标类型: height/weight/bmi',
    `age_months` INT NOT NULL COMMENT '月龄',
    
    -- LMS参数（用于精确计算）
    `l_value` DECIMAL(10,6) COMMENT 'LMS-L参数(Box-Cox power)',
    `m_value` DECIMAL(10,4) COMMENT 'LMS-M参数(中位数)',
    `s_value` DECIMAL(10,6) COMMENT 'LMS-S参数(变异系数)',
    
    -- 百分位数据（直接存储，用于曲线绘制）
    `p3` DECIMAL(10,2) NOT NULL COMMENT '第3百分位',
    `p15` DECIMAL(10,2) NOT NULL COMMENT '第15百分位',
    `p50` DECIMAL(10,2) NOT NULL COMMENT '第50百分位(中位数)',
    `p85` DECIMAL(10,2) NOT NULL COMMENT '第85百分位',
    `p97` DECIMAL(10,2) NOT NULL COMMENT '第97百分位',
    
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    INDEX `idx_type_gender_indicator` (`standard_type_id`, `gender`, `indicator`),
    INDEX `idx_age` (`age_months`),
    UNIQUE KEY `uk_standard_data` (`standard_type_id`, `gender`, `indicator`, `age_months`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='生长标准数据表';

